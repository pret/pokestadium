def replace_once(source: str, old: str, new: str, label: str) -> str:
    count = source.count(old)
    if count != 1:
        raise SystemExit(f"7.1 anchor {label!r} occurred {count} times")
    return source.replace(old, new, 1)


def header71() -> str:
    text = HEADER.replace("DKWB_CDX_COLOR_TABLE\n", color_register_table())
    text = text.replace(
        "Generated by n64-decomp-workbench for the pinned IDO 5.3 static-recomp\n * profile.",
        "Ported to IDO 7.1 by cdx71/patch_uopt71.py (from the workbench's 5.3\n * profile).",
    )
    old, new = ADDR["curproc"]
    assert text.count(f"MEM_U32({old})") == 1
    text = text.replace(f"MEM_U32({old})", f"MEM_U32({new})")
    # 7.1 reuses graphnode+308 for bit-vector headers by globalcolor time
    # (measured: every node read 2 there, while f_init_graphnode had stored
    # 3/5/5/5/5/5 for the microcase). Read the creation-time line instead.
    assert text.count("(int)MEM_U32(graphnode + 308)") == 2
    text = text.replace("(int)MEM_U32(graphnode + 308)", "dkwb_cdx_node_line(graphnode)")
    # Occurrence-qualified forces (p1:w58#2=c24). A split piece keeps its
    # parent's web number, so a plain p1:w58=s also splits every piece; the
    # qualifier applies a force to the Nth decision of that web only.
    old = "    int color = dkwb_cdx_lookup(ordinal, phase, web);\n"
    assert text.count(old) == 1
    text = text.replace(old, "    int color = dkwb_cdx_lookup_occ(ordinal, phase, site, web);\n")
    anchor = "static int dkwb_cdx_color_forbidden("
    assert text.count(anchor) == 1
    text = text.replace(anchor, FORCE_OCCURRENCE + anchor)
    old = (
        "    if (!dkwb_cdx_digits(&cursor)) return 0;\n"
        "    if (*cursor++ != '=') return 0;\n"
    )
    assert text.count(old) == 1
    text = text.replace(old, (
        "    if (!dkwb_cdx_digits(&cursor)) return 0;\n"
        "    if (*cursor == '#') { cursor++; if (!dkwb_cdx_digits(&cursor)) return 0; }\n"
        "    if (*cursor++ != '=') return 0;\n"
    ))
    return text


FORCE_OCCURRENCE = r"""/* p1:wN#K=... matches only the Kth phase-qualified decision of web N (the
 * "dec" site counts; the "color" site that follows reuses the count). An
 * unqualified p1:wN=... still matches every decision. */
#define DKWB_CDX_OCC_WEBS 16384
static int dkwb_cdx_occ[2][DKWB_CDX_OCC_WEBS];
static int dkwb_cdx_lookup_occ(int ordinal, const char *phase, const char *site, int web) {
    char key[48];
    const char *cursor;
    int key_length, occ, slot = phase[1] == '2';
    if (!dkwb_cdx_force[0] || !dkwb_cdx_active(ordinal)) return -2;
    if (web < 0 || web >= DKWB_CDX_OCC_WEBS) return dkwb_cdx_lookup(ordinal, phase, web);
    if (site[0] == 'd') dkwb_cdx_occ[slot][web]++;
    occ = dkwb_cdx_occ[slot][web];
    key_length = snprintf(key, sizeof(key), "%s:w%d#%d=", phase, web, occ);
    cursor = dkwb_cdx_force;
    while ((cursor = strstr(cursor, key)) != NULL) {
        if (cursor == dkwb_cdx_force || cursor[-1] == ',') {
            const char *value = cursor + key_length;
            if (*value == 's') return -1;
            if (*value == 'c') return atoi(value + 1);
        }
        cursor += key_length;
    }
    return dkwb_cdx_lookup(ordinal, phase, web);
}
"""


NODE_LINE_MAP = r"""
/* ---- graph-node creation line (7.1) ----
 * f_init_graphnode stores the current Uloc line (MEM_U32(0x1001c404), set by
 * f_copyline from Uloc +4) at node+308, but 7.1 later overwrites that word.
 * The wrapper below records it host-side so records can report the line the
 * block was created on. Keyed by emulated node address; re-recorded when the
 * allocator reuses an address for a new procedure. */
#define DKWB_NODE_LINES 65536
static uint32_t dkwb_node_key[DKWB_NODE_LINES];
static int32_t dkwb_node_val[DKWB_NODE_LINES];
static void dkwb_cdx_node_line_record(uint32_t node, int32_t line) {
    uint32_t h = (node >> 3) & (DKWB_NODE_LINES - 1), i;
    for (i = 0; i < DKWB_NODE_LINES; i++, h = (h + 1) & (DKWB_NODE_LINES - 1))
        if (dkwb_node_key[h] == 0 || dkwb_node_key[h] == node) {
            dkwb_node_key[h] = node; dkwb_node_val[h] = line; return;
        }
}
static int dkwb_cdx_node_line(uint32_t node) {
    uint32_t h = (node >> 3) & (DKWB_NODE_LINES - 1), i;
    if (node == 0) return -1;
    for (i = 0; i < DKWB_NODE_LINES; i++, h = (h + 1) & (DKWB_NODE_LINES - 1)) {
        if (dkwb_node_key[h] == node) return (int)dkwb_node_val[h];
        if (dkwb_node_key[h] == 0) return -1;
    }
    return -1;
}
"""


def stage_node_lines(src: str) -> str:
    sig = "static void f_init_graphnode(uint8_t *mem, uint32_t sp, uint32_t a0) {\n"
    return replace_once(
        src, sig,
        NODE_LINE_MAP
        + sig.replace("f_init_graphnode", "f_init_graphnode_stock").replace(" {\n", ";\n")
        + sig
        + "    f_init_graphnode_stock(mem, sp, a0);\n"
        "    dkwb_cdx_node_line_record(a0, (int32_t)MEM_U32(a0 + 308));\n}\n"
        + sig.replace("f_init_graphnode", "f_init_graphnode_stock"),
        "init_graphnode wrapper",
    )


