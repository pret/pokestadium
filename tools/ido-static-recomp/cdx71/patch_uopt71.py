#!/usr/bin/env python3
"""Port of the n64-decomp-workbench IDO 5.3 uopt CDX profile to IDO 7.1.

Input : build/7.1/uopt.c generated by decompals/ido-static-recomp at commit
        d5aec59932034b8a20f23f471297a55c45dcbc45 (see PINNED_SHA256).
Output: build/7.1-traced/uopt.gc.c plus one backup per stage, mirroring the
        stage layout of the original hand port:

    uopt.gc.c.bak_ichain   stage 1  globalcolor decisions/costs/forces only
    uopt.gc.c.bak_nodes    stage 2  + lineage (ICHAIN tables), symtab, temps
    uopt.gc.c.pre_cmdump   stage 3  + graph-node dump, incoming u-code dump
    uopt.gc.c              stage 4  + f_optinit code-motion dump hook

The record grammar and CDX_* switches are the workbench's (HEADER and the force
parser are imported from decomp_workbench.instrument_uopt so the reader and
the producer cannot drift).  Every 7.1 anchor and emulated address below was
re-derived from the 7.1 generated source; the derivation is recorded next to
each one.  Struct field offsets (liverange, ichain, graphnode, itable) are
carried over from the 5.3 profile and are *assumed* unchanged between 5.3 and
7.1; the positive controls in README-cdx71.md are what checks them.

Usage: python3 cdx71/patch_uopt71.py build/7.1/uopt.c build/7.1-traced
"""

